"""Generates a Markdown datasheet from registry metadata and manifest counts."""

from datetime import date
from pathlib import Path


def _table(headers: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def render(name: str, entry: dict, report: dict, stats: dict, prepared_on: date) -> str:
    lines = [
        f"# Data card: {entry['title']}",
        "",
        f"Generated by `ml/common/prepare.py` on {prepared_on.isoformat()}. Do not edit by hand.",
        "",
        "## Summary",
        "",
        f"- **Dataset id:** `{name}`",
        f"- **Modality:** {entry['modality']}",
        f"- **Role:** {entry['role']}",
        f"- **Licence:** {entry['licence']}",
        f"- **Access:** {entry['access']}",
        f"- **Homepage:** {entry['homepage']}",
        f"- **Samples after preparation:** {report['total']:,}",
        "",
        "## Classes and splits",
        "",
    ]
    lines += _table(
        ["Split", "Samples", "Real", "Fake", "Fake share", "Groups"],
        [
            [split, f"{row['samples']:,}", f"{row['real']:,}", f"{row['fake']:,}", row["fake_share"], f"{row['groups']:,}"]
            for split, row in report["splits"].items()
        ],
    )

    split_names = list(report["splits"])
    lines += ["", "## Sources and generators", ""]
    lines += _table(
        ["Generator", *split_names],
        [
            [generator, *(f"{counts.get(split, 0):,}" for split in split_names)]
            for generator, counts in report["generators"].items()
        ],
    )

    lines += ["", "## Preparation", ""]
    lines += [f"- {key.replace('_', ' ').capitalize()}: {value:,}" for key, value in stats.items()]

    lines += ["", "## Known biases", ""]
    lines += [f"- {bias}" for bias in entry["known_biases"]]
    return "\n".join(lines) + "\n"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
